function [result,events,info] = decodeBufferedLeverTrial(snapshot,firstTrialArduinoMs)
% Decode an immutable BATCH snapshot, using board time rather than USB timing.
% A packed word stores (elapsed milliseconds << 1) | (lever ID - 1).
if nargin<2, firstTrialArduinoMs = snapshot.ArduinoStartMs; end
numericNames = {'Trial','StoredPresses','DroppedPresses','Completed','WaterDelivered', ...
    'Acknowledged','ArduinoStartMs','ArduinoEndMs','Lever1Presses','Lever2Presses', ...
    'ActivePresses','WindowStartMs','WindowEndMs','SolenoidMs'};
for k=1:numel(numericNames)
    validateattributes(snapshot.(numericNames{k}),{'numeric','logical'}, ...
        {'scalar','finite','integer','nonnegative'});
end
assert(ismember(string(snapshot.TaskMode),["TRIAL","WINDOW"]),'Invalid snapshot task.');
assert(ismember(string(snapshot.ActiveLevers),["BOTH","LEVER1","LEVER2"]),'Invalid lever selection.');
assert(snapshot.Trial>=1 && snapshot.StoredPresses<=1024,'Invalid trial/capture count.');
assert(all(ismember([snapshot.Completed snapshot.WaterDelivered snapshot.Acknowledged],[0 1])), ...
    'Invalid result flags.');
assert(snapshot.ArduinoStartMs<2^32 && snapshot.ArduinoEndMs<2^32,'Invalid Arduino clock.');
assert(snapshot.WindowStartMs<snapshot.WindowEndMs && snapshot.WindowEndMs<=3600000, ...
    'Invalid response window.');
words = double(snapshot.PackedPresses(:));
assert(numel(words)==snapshot.StoredPresses && all(isfinite(words)) && ...
    all(words>=0) && all(words==fix(words)) && all(words<2^32),'Invalid packed press data.');
elapsed = floor(words/2); lever = mod(words,2)+1;
duration = mod(snapshot.ArduinoEndMs-snapshot.ArduinoStartMs,2^32);
assert(all(elapsed<=3600000) && all(diff(elapsed)>=0),'Press times are invalid or out of order.');
if snapshot.Completed
    assert(snapshot.WindowEndMs<=duration,'Completed interval ends before its response window.');
    assert(all(elapsed<duration),'Completed-trial press falls outside its captured interval.');
else
    assert(all(elapsed<=duration),'Aborted-trial press falls after its abort time.');
end
selected = repmat(string(snapshot.ActiveLevers)=="BOTH",size(lever));
selected = selected | (lever==1 & string(snapshot.ActiveLevers)=="LEVER1") | ...
    (lever==2 & string(snapshot.ActiveLevers)=="LEVER2");
phase = repmat("TRIAL",size(lever));
if string(snapshot.TaskMode)=="WINDOW"
    phase(:) = "WINDOW";
    phase(elapsed<snapshot.WindowStartMs) = "EARLY";
    phase(elapsed>=snapshot.WindowEndMs) = "LATE";
end
qualifying = selected & ismember(phase,["TRIAL","WINDOW"]);
assert(snapshot.ActivePresses<=snapshot.Lever1Presses+snapshot.Lever2Presses,'Invalid selected-press count.');
assert(snapshot.WaterDelivered==double(snapshot.Completed && snapshot.ActivePresses>0), ...
    'Snapshot reward command disagrees with the task rule.');
assert(snapshot.StoredPresses+snapshot.DroppedPresses==snapshot.Lever1Presses+snapshot.Lever2Presses, ...
    'Device count and retained/dropped events disagree.');
countsMatch = sum(lever==1)==snapshot.Lever1Presses && ...
    sum(lever==2)==snapshot.Lever2Presses && sum(qualifying)==snapshot.ActivePresses;
if snapshot.DroppedPresses==0
    assert(countsMatch,'Press events disagree with the device trial counts.');
else
    assert(sum(lever==1)<=snapshot.Lever1Presses && sum(lever==2)<=snapshot.Lever2Presses && ...
        sum(qualifying)<=snapshot.ActivePresses,'Dropped-event counts are inconsistent.');
end
arduinoMs = mod(snapshot.ArduinoStartMs+elapsed,2^32);
sessionSeconds = mod(arduinoMs-firstTrialArduinoMs,2^32)/1000;
events = table(repmat(snapshot.Trial,size(lever)),lever,arduinoMs,elapsed,elapsed/1000, ...
    sessionSeconds,true(size(lever)),logical(selected),logical(qualifying),phase, ...
    repmat(snapshot.HostReadoutAt,size(lever)), ...
    'VariableNames',{'Trial','LeverID','ArduinoMs','TrialElapsedMs','TrialTimeSeconds', ...
    'SessionTimeSeconds','InTrial','SelectedLever','Qualifying','Phase','HostReceivedAt'});
completeEvents = countsMatch && snapshot.DroppedPresses==0;
result = table(snapshot.Trial,NaT,NaT,snapshot.Lever1Presses+snapshot.Lever2Presses, ...
    double(snapshot.ActivePresses>0),snapshot.WaterDelivered,snapshot.Lever1Presses, ...
    snapshot.Lever2Presses,snapshot.ActivePresses,snapshot.ActivePresses,logical(snapshot.Completed), ...
    snapshot.ArduinoStartMs,snapshot.ArduinoEndMs,string(snapshot.ActiveLevers), ...
    double(snapshot.ActivePresses>0),snapshot.WindowStartMs,snapshot.WindowEndMs, ...
    snapshot.WindowEndMs-snapshot.WindowStartMs, ...
    sum(lever==1 & phase=="EARLY"),sum(lever==2 & phase=="EARLY"), ...
    sum(lever==1 & phase=="WINDOW"),sum(lever==2 & phase=="WINDOW"), ...
    sum(lever==1 & phase=="LATE"),sum(lever==2 & phase=="LATE"), ...
    snapshot.Lever1Presses+snapshot.Lever2Presses-snapshot.ActivePresses, ...
    snapshot.StoredPresses,snapshot.DroppedPresses,completeEvents,snapshot.HostReadoutAt, ...
    'VariableNames',{'Trial','TrialStart','TrialEnd','PressCount','SawActivePress','WaterDelivered', ...
    'Lever1Presses','Lever2Presses','ActivePresses','QualifyingPresses','Completed', ...
    'ArduinoStartMs','ArduinoEndMs','ActiveLevers','SawQualifyingPress','WindowStartMs', ...
    'WindowEndMs','WindowLengthMs','EarlyLever1Presses','EarlyLever2Presses','WindowLever1Presses', ...
    'WindowLever2Presses','LateLever1Presses','LateLever2Presses','NonQualifyingPresses', ...
    'CapturedPresses','DroppedPresses','EventsComplete','HostReadoutAt'});
info = struct('ProtocolVersion',2,'Transport',"BATCH",'CaptureScope',"In-trial presses only", ...
    'CapacityPerTrial',1024,'TimestampResolutionMs',1,'DebounceMs',10, ...
    'TrialCountsMatch',countsMatch,'EventsComplete',completeEvents, ...
    'DroppedPresses',snapshot.DroppedPresses,'DeviceSolenoidMs',snapshot.SolenoidMs, ...
    'HostTimeMeaning',"HostReceivedAt is batch readout time; TrialStart/TrialEnd are NaT", ...
    'SessionStartArduinoMs',firstTrialArduinoMs);
end
